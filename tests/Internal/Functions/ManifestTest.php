<?php

declare(strict_types=1);

namespace Polidog\Rosanna\Defer\Tests\Internal\Functions;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

use function Polidog\Rosanna\Defer\Internal\Functions\deferredManifestEntries;
use function Polidog\Rosanna\Defer\Internal\Functions\deferredManifestSource;

use Polidog\Rosanna\Runtime\PsxRenderer;

final class ManifestTest extends TestCase
{
    public function testSourceIsSortedByNameAndStartsWithTheBuildId(): void
    {
        $source = deferredManifestSource('b1', [
            'b' => ['component' => 'App\\B', 'cacheControl' => null],
            404 => ['component' => 'App\\NotFound', 'cacheControl' => 'public, max-age=60'],
            'a' => ['component' => "App\\A'", 'cacheControl' => null],
        ]);

        self::assertSame(implode("\n", [
            '<?php',
            '// Auto-generated by `rosanna-defer compile` or `rosanna-state compile`. Do not edit.',
            'return [',
            '    ' . var_export(PsxRenderer::BUILD_ID_KEY, true) . " => 'b1',",
            "    '404' => ['component' => 'App\\\\NotFound', 'cacheControl' => 'public, max-age=60'],",
            "    'a' => ['component' => 'App\\\\A\\'', 'cacheControl' => NULL],",
            "    'b' => ['component' => 'App\\\\B', 'cacheControl' => NULL],",
            '];',
        ]) . "\n", $source);
    }

    public function testSourceWithoutEntriesHasOnlyTheBuildId(): void
    {
        self::assertSame(
            "<?php\n// Auto-generated by `rosanna-defer compile` or `rosanna-state compile`. Do not edit.\nreturn [\n    "
            . var_export(PsxRenderer::BUILD_ID_KEY, true) . " => 'b1',\n];\n",
            deferredManifestSource('b1', []),
        );
    }

    public function testEntriesRoundTripTheSource(): void
    {
        $entries = [
            '404' => ['component' => 'App\\NotFound', 'cacheControl' => 'public'],
            'a' => ['component' => 'App\\A', 'cacheControl' => null],
        ];
        $path = (string) tempnam(sys_get_temp_dir(), 'rosanna-defer-manifest');
        try {
            file_put_contents($path, deferredManifestSource('b1', $entries));
            $data = require $path;
        } finally {
            unlink($path);
        }
        self::assertIsArray($data);

        self::assertSame($entries, deferredManifestEntries($data, 'deferred.php'));
    }

    /** @return iterable<string, array{mixed}> */
    public static function badEntries(): iterable
    {
        yield 'not an array' => ['App\\A'];
        yield 'no component' => [['cacheControl' => null]];
        yield 'component is not a string' => [['component' => 1, 'cacheControl' => null]];
        yield 'cacheControl is not a string' => [['component' => 'App\\A', 'cacheControl' => 60]];
    }

    #[DataProvider('badEntries')]
    public function testEntriesRefuseAnEntryOfTheWrongShape(mixed $entry): void
    {
        $this->expectException(\RuntimeException::class);
        $this->expectExceptionMessage('Invalid deferred manifest entry in deferred.php.');
        deferredManifestEntries(['a' => $entry], 'deferred.php');
    }

    public function testAMissingCacheControlIsNull(): void
    {
        self::assertSame(['a' => ['component' => 'App\\A', 'cacheControl' => null]], deferredManifestEntries(['a' => ['component' => 'App\\A']], 'deferred.php'));
    }
}
