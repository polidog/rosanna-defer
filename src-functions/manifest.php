<?php

declare(strict_types=1);

namespace Polidog\Rosanna\Defer\Internal\Functions;

/*
 * ここの関数は @internal で、公開 API ではない。rosanna シリーズ (polidog/rosanna-*) からは使ってよいが、
 * それ以外からは使わない。互換性はシリーズの中でだけ揃える。
 */

use Polidog\Rosanna\Runtime\PsxRenderer;

/**
 * deferred manifest の中身。名前の順に並べるので、登録の順が変わっても同じ内容になる
 *
 * @internal
 * @param array<array-key, array{component: string, cacheControl: ?string}> $entries 名前 => 登録の内容
 */
function deferredManifestSource(string $buildId, array $entries): string
{
    \ksort($entries, \SORT_STRING);
    $lines = ['<?php', '// Auto-generated by `rosanna-defer compile` or `rosanna-state compile`. Do not edit.', 'return ['];
    $lines[] = '    ' . \var_export(PsxRenderer::BUILD_ID_KEY, true) . ' => ' . \var_export($buildId, true) . ',';
    foreach ($entries as $name => $entry) {
        $lines[] = '    ' . \var_export((string) $name, true) . ' => ['
            . "'component' => " . \var_export($entry['component'], true)
            . ", 'cacheControl' => " . \var_export($entry['cacheControl'], true)
            . '],';
    }
    $lines[] = '];';

    return \implode("\n", $lines) . "\n";
}

/**
 * deferred manifest が返した配列から登録の内容を取り出す。build ID の項目は除く。照合は呼び出し側がする
 *
 * @internal
 * @param array<mixed> $data
 * @return array<string, array{component: string, cacheControl: ?string}> 名前 => 登録の内容
 * @throws \RuntimeException 項目の形が違うとき
 */
function deferredManifestEntries(array $data, string $path): array
{
    unset($data[PsxRenderer::BUILD_ID_KEY]);

    $deferred = [];
    foreach ($data as $name => $entry) {
        $cacheControl = \is_array($entry) ? ($entry['cacheControl'] ?? null) : null;
        // `404` のような数字だけの名前は PHP の配列のキーで整数になる
        if (!\is_array($entry) || !\is_string($entry['component'] ?? null) || (!\is_string($cacheControl) && $cacheControl !== null)) {
            throw new \RuntimeException("Invalid deferred manifest entry in {$path}. Run `vendor/bin/rosanna-defer compile` or `vendor/bin/rosanna-state compile` to regenerate.");
        }
        $deferred[(string) $name] = ['component' => $entry['component'], 'cacheControl' => $cacheControl];
    }

    return $deferred;
}
